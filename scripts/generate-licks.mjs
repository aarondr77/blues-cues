/**
 * Writes the hand-authored lick library to src/licks/*.json.
 *
 * The licks are written here as fret/string pairs (how a guitarist thinks about
 * them) and the MIDI numbers are derived, which keeps the two from drifting
 * apart. Re-run with `npm run licks` after editing.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../src/licks');

/** Standard tuning, string 1 = high E. MIDI of each open string. */
const OPEN_STRINGS = { 1: 64, 2: 59, 3: 55, 4: 50, 5: 45, 6: 40 };

const midiOf = (string, fret) => OPEN_STRINGS[string] + fret;

/** `n(string, fret, beat, duration)` */
const n = (string, fret, beat, duration) => ({
  midi: midiOf(string, fret),
  string,
  fret,
  beat,
  duration,
});

